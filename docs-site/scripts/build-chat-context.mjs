#!/usr/bin/env node
// Build-time script that concatenates every docs page and article
// into a single plain-text context file the chat Worker embeds as
// its grounding corpus.
//
// Output:
//   workers/chat/src/context.generated.ts — exports DOCS_CONTEXT
//
// Strategy: strip YAML frontmatter and MDX-specific imports, keep
// prose + headings + code fences. Tags each section with its URL
// so the model can cite pages by path.

import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const siteRoot = path.resolve(__dirname, '..');
const repoRoot = path.resolve(siteRoot, '..');

const DOCS_DIR = path.join(siteRoot, 'content/docs');
const ARTICLES_DIR = path.join(siteRoot, 'content/articles');
const OUTPUT = path.join(repoRoot, 'workers/chat/src/context.generated.ts');

// Strip frontmatter and noisy MDX bits while keeping semantic content.
function cleanMdx(raw) {
  let text = raw;
  text = text.replace(/^---\n[\s\S]*?\n---\n?/, '');
  text = text.replace(/^import\s+[^\n]+\n?/gm, '');
  text = text.replace(/<Mermaid\s+chart=\{`[\s\S]*?`\}\s*\/>/g, '');
  text = text.replace(/<Callout[\s\S]*?<\/Callout>/g, (m) =>
    m.replace(/<\/?Callout[^>]*>/g, ''),
  );
  text = text.replace(/<Cards>[\s\S]*?<\/Cards>/g, '');
  text = text.replace(/\n{3,}/g, '\n\n');
  return text.trim();
}

async function walk(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  const entries = await readdir(dir, { withFileTypes: true });
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      out.push(...(await walk(full)));
    } else if (e.name.endsWith('.mdx') || e.name.endsWith('.md')) {
      out.push(full);
    }
  }
  return out;
}

function urlFor(kind, filePath) {
  const base = kind === 'docs' ? DOCS_DIR : ARTICLES_DIR;
  const rel = path.relative(base, filePath).replace(/\.mdx?$/, '');
  const slug = rel === 'index' ? '' : rel;
  const prefix = kind === 'docs' ? '/docs' : '/articles';
  return slug ? `${prefix}/${slug}` : prefix;
}

async function buildSection(kind, files) {
  const parts = [];
  for (const f of files.sort()) {
    const raw = await readFile(f, 'utf8');
    const frontmatter = raw.match(/^---\n([\s\S]*?)\n---/)?.[1] || '';
    const title = frontmatter.match(/^title:\s*(.+)$/m)?.[1]?.trim() || '';
    const description =
      frontmatter.match(/^description:\s*(.+)$/m)?.[1]?.trim() || '';
    const url = urlFor(kind, f);
    const body = cleanMdx(raw);

    parts.push(
      [
        `=== ${kind.toUpperCase()} PAGE: ${title} ===`,
        `URL: ${url}`,
        description ? `Description: ${description}` : null,
        '',
        body,
      ]
        .filter(Boolean)
        .join('\n'),
    );
  }
  return parts.join('\n\n---\n\n');
}

async function main() {
  const docsFiles = await walk(DOCS_DIR);
  const articleFiles = await walk(ARTICLES_DIR);

  const docsBlock = await buildSection('docs', docsFiles);
  const articlesBlock = await buildSection('article', articleFiles);

  const full = [
    '# speckit-security documentation corpus',
    '',
    'This is the complete grounding corpus for the speckit-security docs chat.',
    'It contains every docs page and article as of build time. Cite URLs when',
    'answering. If the answer is not in this corpus, say so plainly.',
    '',
    '## DOCS',
    '',
    docsBlock,
    '',
    '## ARTICLES',
    '',
    articlesBlock,
  ].join('\n');

  const byteLen = Buffer.byteLength(full, 'utf8');

  await mkdir(path.dirname(OUTPUT), { recursive: true });
  const escaped = full.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
  const ts = [
    '// AUTO-GENERATED by docs-site/scripts/build-chat-context.mjs',
    '// Do not edit by hand. Re-run `pnpm build:chat-context`.',
    '',
    `export const DOCS_CONTEXT = \`${escaped}\`;`,
    '',
    `export const DOCS_CONTEXT_BYTES = ${byteLen};`,
    '',
  ].join('\n');
  await writeFile(OUTPUT, ts);

  const approxTokens = Math.ceil(byteLen / 4);
  console.log(
    `✓ wrote ${OUTPUT.replace(repoRoot + '/', '')} (${byteLen} bytes, ~${approxTokens} tokens)`,
  );
  console.log(`  docs pages:     ${docsFiles.length}`);
  console.log(`  article pages:  ${articleFiles.length}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
